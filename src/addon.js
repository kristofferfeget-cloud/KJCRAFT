// Builds the CraftPath addon's data file (Lua) and a downloadable zip from the live route payload.
import { deflateRawSync } from 'node:zlib';

const BOLTS = { 2996: [2589, 2], 2997: [2592, 3], 4305: [4306, 4], 4339: [4338, 5], 14048: [14047, 5] };

// Lua string literal (Lua 5.1 has no \u escapes, so control characters become \ddd).
function luaStr(s) {
  let out = '"';
  for (const ch of String(s)) {
    const c = ch.codePointAt(0);
    if (ch === '\\') out += '\\\\';
    else if (ch === '"') out += '\\"';
    else if (ch === '\n') out += '\\n';
    else if (c < 32 || c === 127) out += '\\' + c;
    else out += ch;
  }
  return out + '"';
}
function luaVal(v) {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'number') return Number.isFinite(v) ? String(Math.round(v * 10) / 10) : 'nil';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'string') return luaStr(v);
  if (Array.isArray(v)) return '{' + v.map(luaVal).join(',') + '}';
  return '{' + Object.entries(v).map(([k, x]) => (/^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : '[' + luaStr(k) + ']') + '=' + luaVal(x)).join(',') + '}';
}
const idMap = (obj, fn) => '{' + Object.entries(obj).map(([k, v]) => `[${+k}]=${fn(v)}`).join(',') + '}';

const money = (c) => { c = Math.round(c); const g = Math.floor(c / 10000), s = Math.floor(c / 100) % 100; return g >= 10 ? `${g}g` : g ? `${g}g ${s}s` : `${s}s`; };

// One short English hint per result item, shown in the addon.
function notesFor(payload) {
  const notes = {}, cooldown = {};
  const add = (id, text) => { if (id && text && !notes[id]) notes[id] = text; };
  for (const p of Object.values(payload.profs)) {
    for (const g of p.gold) {
      const [, rid, , , , , , sold, flag, rep, pat] = g;
      if (flag === 'cd') cooldown[rid] = true;
      if (flag === 'spec') add(rid, 'Needs Gnomish/Goblin specialization.');
      else if (flag === 'cd') add(rid, 'Has a cooldown.');
      else if (rep) add(rid, `Needs ${rep} reputation.`);
      else if (pat) add(rid, `Pattern about ${money(pat)} on the AH.`);
      else if (sold != null && sold < 10) add(rid, `Only ~${Math.round(sold * 10) / 10} sell per day – spread your sales.`);
    }
    for (const v of ['best', 'trainer']) {
      for (const st of p[v]) {
        const rid = st[3], how = st[14], sold = st[15], vend = st[16], thin = st[18], ah = st[19], liquid = st[21];
        if (!rid) continue;
        if (thin === 1) add(rid, 'Some mats are barely on the AH – the price may not hold.');
        else if (how === 'vendor' && ah != null && !liquid) add(rid, `AH price ignored (only ~${Math.round((sold || 0) * 10) / 10} sold per day) – vendor it.`);
        else if (how === 'vendor' && ah != null && vend > ah) add(rid, 'A vendor pays more than the AH.');
        else if (st[10] > 0) add(rid, `Pattern about ${money(st[10])} on the AH.`);
      }
    }
  }
  return { notes, cooldown };
}

/** The addon's Data.lua for a route payload. */
export function buildDataLua(payload, baseUrl) {
  const scanned = payload.scannedAt || payload.generatedAt;
  const ts = (iso) => (iso ? Math.floor(new Date(iso).getTime() / 1000) : 0);
  const names = {}, quality = {};
  for (const [id, [name, q]] of Object.entries(payload.items || {})) { names[id] = name; quality[id] = q; }
  const { notes, cooldown } = notesFor(payload);
  const f = payload.filters || { minSold: 3, minListed: 5, cut: 5 };
  const L = [];
  L.push('-- CraftPath data: routes, gold tips and AH prices for WoW: Forever.');
  L.push(`-- Generated by ${baseUrl} – ${payload.generatedAt || ''}. AH scan ${scanned || ''}.`);
  L.push('-- Do not edit: the updater replaces this file. Get a fresh copy from the website.');
  L.push('--');
  L.push('-- Route step: {from, to, name, itemID, yield, learn, yellow, green, grey, source, patternPrice, crafts,');
  L.push('--              matsPerCraft, salePerCraft, saleType, soldPerDay, vendorPerCraft, {{reagentID, qty}, ...},');
  L.push('--              thinMarket, ahValuePerCraft, listed, ahUsable}');
  L.push('-- Gold entry: {name, itemID, yield, learn, source, matsPerCraft, salePerCraft, soldPerDay, flag, reputation, patternPrice, {{reagentID, qty}, ...}}');
  L.push('');
  L.push('local _, ns = ...');
  L.push('local R = {}');
  L.push('ns.RAW = R');
  L.push('R.v = 2');
  L.push('R.source = "AHledger"');
  L.push(`R.market = ${luaStr(payload.market || 'Normal Alliance EU')}`);
  L.push(`R.url = ${luaStr(baseUrl)}`);
  L.push(`R.live = ${payload.source === 'live' ? 'true' : 'false'}`);
  L.push(`R.generatedTs = ${ts(payload.generatedAt)}`);
  L.push(`R.scannedTs = ${ts(scanned)}`);
  L.push(`R.asOf = ${luaStr(payload.asOf || '')}`);
  L.push(`R.refreshMinutes = ${payload.refreshMinutes || 30}`);
  L.push(`R.filters = ${luaVal({ minSold: f.minSold, minListed: f.minListed, cut: f.cut })}`);
  L.push('R.profs = {}');
  for (const [slug, p] of Object.entries(payload.profs)) {
    L.push(`R.profs[${luaStr(slug)}] = {`);
    for (const v of ['best', 'trainer']) {
      L.push(`  ${v} = {`);
      for (const st of p[v]) L.push('    ' + luaVal(st.slice(0, 22).concat(Array(Math.max(0, 22 - st.length)).fill(null))) + ',');
      L.push('  },');
    }
    L.push('  gold = {');
    for (const g of p.gold) L.push('    ' + luaVal(g) + ',');
    L.push('  },');
    L.push('}');
  }
  L.push(`R.names = ${idMap(names, luaStr)}`);
  L.push(`R.quality = ${idMap(quality, (q) => String(q))}`);
  L.push(`R.price = ${idMap(payload.prices || {}, (p) => luaVal([p[0], p[1], p[2] ?? null, p[3] ?? null]))}`);
  L.push(`R.bolts = ${idMap(BOLTS, luaVal)}`);
  L.push(`R.notes = ${idMap(notes, luaStr)}`);
  L.push(`R.cooldown = ${idMap(cooldown, () => 'true')}`);
  L.push('');
  return L.join('\n');
}

// ---------- minimal zip writer (deflate) ----------
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** files: [{ name: 'CraftPath/Core.lua', data: Buffer|string }] */
export function buildZip(files, date = new Date()) {
  const dosTime = ((date.getHours() << 11) | (date.getMinutes() << 5) | Math.floor(date.getSeconds() / 2)) & 0xffff;
  const dosDate = (((date.getFullYear() - 1980) << 9) | ((date.getMonth() + 1) << 5) | date.getDate()) & 0xffff;
  const locals = [], centrals = [];
  let offset = 0;
  for (const f of files) {
    const name = Buffer.from(f.name, 'utf8');
    const raw = Buffer.isBuffer(f.data) ? f.data : Buffer.from(f.data, 'utf8');
    const comp = deflateRawSync(raw, { level: 9 });
    const crc = crc32(raw);
    const lh = Buffer.alloc(30);
    lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0x0800, 6); lh.writeUInt16LE(8, 8);
    lh.writeUInt16LE(dosTime, 10); lh.writeUInt16LE(dosDate, 12); lh.writeUInt32LE(crc, 14);
    lh.writeUInt32LE(comp.length, 18); lh.writeUInt32LE(raw.length, 22); lh.writeUInt16LE(name.length, 26); lh.writeUInt16LE(0, 28);
    locals.push(lh, name, comp);
    const ch = Buffer.alloc(46);
    ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0x0800, 8); ch.writeUInt16LE(8, 10);
    ch.writeUInt16LE(dosTime, 12); ch.writeUInt16LE(dosDate, 14); ch.writeUInt32LE(crc, 16);
    ch.writeUInt32LE(comp.length, 20); ch.writeUInt32LE(raw.length, 24); ch.writeUInt16LE(name.length, 28);
    ch.writeUInt16LE(0, 30); ch.writeUInt16LE(0, 32); ch.writeUInt16LE(0, 34); ch.writeUInt16LE(0, 36); ch.writeUInt32LE(0, 38); ch.writeUInt32LE(offset, 42);
    centrals.push(ch, name);
    offset += lh.length + name.length + comp.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}
